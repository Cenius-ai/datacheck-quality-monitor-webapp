#!/usr/bin/env bash
# Datacheck Quality Monitor — project-level install.
# Installs Python dependencies, creates a .env with a generated SESSION_SECRET
# (only when missing), seeds the demo database and exits. Never starts a server.
set -euo pipefail
cd "$(dirname "$0")"

PYTHON="${PYTHON:-python3}"

echo "==> Installing Python dependencies"
"$PYTHON" -m pip install --upgrade pip setuptools wheel
"$PYTHON" -m pip install -r requirements.txt

if [ ! -f .env ]; then
  echo "==> Writing .env with a generated SESSION_SECRET"
  SECRET="$("$PYTHON" -c 'import secrets; print(secrets.token_hex(32))')"
  {
    echo "# Generated by install.sh — adjust before a production deploy."
    echo "SESSION_SECRET=${SECRET}"
    echo "DATABASE_URL=sqlite:///./datacheck.db"
    echo "PORT=8050"
  } > .env
elif ! grep -q '^SESSION_SECRET=.\+' .env; then
  echo "==> Adding a generated SESSION_SECRET to the existing .env"
  SECRET="$("$PYTHON" -c 'import secrets; print(secrets.token_hex(32))')"
  printf 'SESSION_SECRET=%s\n' "${SECRET}" >> .env
fi

echo "==> Seeding demo data (idempotent)"
"$PYTHON" -m datacheck.seed

echo "==> Verifying the application imports cleanly"
"$PYTHON" -c "import app; print('app import ok:', app.app.title)"

echo
echo "Install complete. Start the dashboard with:  python3 app.py"
echo "Then open http://localhost:8050 and sign in with cenius@cenius.ai / cenius"
